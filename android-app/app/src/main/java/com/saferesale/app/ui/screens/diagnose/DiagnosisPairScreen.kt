package com.saferesale.app.ui.screens.diagnose

import android.content.Context
import android.os.Build
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextAlign
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.saferesale.app.data.ApiClient
import com.saferesale.app.diagnostics.CoreVScoreReport
import kotlinx.coroutines.launch

/**
 * DiagnosisPairScreen
 *
 * Runs on the device undergoing diagnosis (the device being sold).
 * 1. User enters the short-lived pairing token generated by the listing device.
 * 2. Securely pairs with the backend (/diagnosis/pair), binding this device's telemetry.
 * 3. Executes the 15 hardware diagnostic modules on THIS device.
 * 4. Submits the verified test report to the backend (/diagnosis/sessions/{id}/results).
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun DiagnosisPairScreen(
    initialToken: String = "",
    onBack: () -> Unit,
    onComplete: () -> Unit,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()

    var tokenInput by remember { mutableStateOf(initialToken) }
    var stage by remember { mutableStateOf("input") } // input | pairing | testing | submitting | complete | error
    var sessionId by remember { mutableStateOf<String?>(null) }
    var listingId by remember { mutableStateOf<String?>(null) }
    var category by remember { mutableStateOf("mobile") }
    var statusText by remember { mutableStateOf("") }
    var errorMessage by remember { mutableStateOf<String?>(null) }
    var diagnosticScore by remember { mutableStateOf<Int?>(null) }
    var testsCount by remember { mutableStateOf(0) }

    fun startPairingAndTests() {
        val rawToken = tokenInput.trim()
        if (rawToken.isBlank()) {
            errorMessage = "Please enter the pairing token"
            return
        }
        stage = "pairing"
        statusText = "Pairing with listing..."
        errorMessage = null

        scope.launch {
            try {
                val deviceInfo = mapOf(
                    "model" to "${Build.MANUFACTURER} ${Build.MODEL}",
                    "manufacturer" to Build.MANUFACTURER,
                    "os_version" to "Android ${Build.VERSION.RELEASE}",
                    "sdk" to Build.VERSION.SDK_INT,
                    "brand" to Build.BRAND,
                    "device" to Build.DEVICE,
                )
                val pairRes = ApiClient.service.pairDiagnosis(
                    mapOf(
                        "token" to rawToken,
                        "device" to deviceInfo,
                        "device_id" to "${Build.MANUFACTURER}_${Build.MODEL}_${Build.SERIAL.take(6)}",
                    )
                )
                val sess = pairRes["session"] as? Map<*, *>
                val sid = sess?.get("_id")?.toString() ?: ""
                val lid = pairRes["listing_id"]?.toString() ?: ""
                val cat = pairRes["category"]?.toString() ?: "mobile"
                sessionId = sid
                listingId = lid
                category = cat

                // Set status to in_progress
                try {
                    ApiClient.service.reportDiagnosisProgress(sid, mapOf("token" to rawToken))
                } catch (_: Exception) {}

                // Stage: testing on THIS hardware
                stage = "testing"
                statusText = "Running 15 hardware benchmark tests on this device..."

                val report = CoreVScoreReport.build(context, category, touchCovered = 9)
                testsCount = report.tests.size

                stage = "submitting"
                statusText = "Submitting verified diagnostics to backend..."

                val payloadTests = report.tests.map {
                    mapOf(
                        "id" to it.id,
                        "status" to it.status,
                        "value" to it.value,
                        "unit" to it.unit,
                        "simulated" to it.simulated,
                        "measured_at" to it.measured_at,
                        "meta" to it.meta,
                    )
                }

                val subRes = ApiClient.service.submitDiagnosisResults(
                    sid,
                    mapOf(
                        "token" to rawToken,
                        "category" to category,
                        "device" to deviceInfo,
                        "tests" to payloadTests,
                    )
                )

                diagnosticScore = (subRes["diagnostic_score"] as? Number)?.toInt()
                stage = "complete"
                statusText = "Diagnosis completed and synced with listing!"
            } catch (e: Exception) {
                errorMessage = e.message ?: "Diagnosis pairing failed"
                stage = "error"
            }
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("SafeResale Diagnosis App") },
                navigationIcon = {
                    IconButton(onClick = onBack) { Text("\u2190") }
                }
            )
        }
    ) { pad ->
        Column(
            Modifier
                .fillMaxSize()
                .padding(pad)
                .padding(24.dp)
                .verticalScroll(rememberScrollState()),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center
        ) {
            when (stage) {
                "input" -> {
                    Text(
                        "Device Pairing",
                        fontSize = 22.sp,
                        fontWeight = FontWeight.Bold,
                        textAlign = TextAlign.Center
                    )
                    Spacer(Modifier.height(8.dp))
                    Text(
                        "Enter the 16-character pairing token displayed on the listing device to begin diagnostics on this device.",
                        textAlign = TextAlign.Center,
                        fontSize = 14.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Spacer(Modifier.height(24.dp))
                    OutlinedTextField(
                        value = tokenInput,
                        onValueChange = { tokenInput = it },
                        label = { Text("Pairing Token") },
                        placeholder = { Text("e.g. 7qX_a92Bz...") },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth(),
                        textStyle = LocalTextStyle.current.copy(fontFamily = FontFamily.Monospace, fontSize = 18.sp),
                    )
                    if (errorMessage != null) {
                        Spacer(Modifier.height(8.dp))
                        Text(errorMessage!!, color = MaterialTheme.colorScheme.error, fontSize = 13.sp)
                    }
                    Spacer(Modifier.height(24.dp))
                    Button(
                        onClick = { startPairingAndTests() },
                        modifier = Modifier.fillMaxWidth().height(50.dp)
                    ) {
                        Text("Connect & Start Diagnosis")
                    }
                }
                "pairing", "testing", "submitting" -> {
                    CircularProgressIndicator(strokeWidth = 4.dp, modifier = Modifier.size(56.dp))
                    Spacer(Modifier.height(20.dp))
                    Text(
                        when (stage) {
                            "pairing" -> "Pairing device..."
                            "testing" -> "Running hardware tests..."
                            else -> "Submitting results..."
                        },
                        fontSize = 18.sp,
                        fontWeight = FontWeight.SemiBold
                    )
                    Spacer(Modifier.height(8.dp))
                    Text(statusText, textAlign = TextAlign.Center, fontSize = 13.sp)
                    Spacer(Modifier.height(16.dp))
                    Card(Modifier.fillMaxWidth()) {
                        Column(Modifier.padding(16.dp)) {
                            Text("Testing on: ${Build.MANUFACTURER} ${Build.MODEL}", fontSize = 13.sp, fontWeight = FontWeight.Medium)
                            Text("OS: Android ${Build.VERSION.RELEASE} (SDK ${Build.VERSION.SDK_INT})", fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                            if (listingId != null) {
                                Text("Listing ID: ${listingId?.take(8)}...", fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                            }
                        }
                    }
                }
                "complete" -> {
                    Text("Diagnosis Complete!", fontSize = 22.sp, fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary)
                    Spacer(Modifier.height(8.dp))
                    Text(statusText, textAlign = TextAlign.Center, fontSize = 14.sp)
                    Spacer(Modifier.height(20.dp))
                    Card(Modifier.fillMaxWidth(), colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.primaryContainer)) {
                        Column(Modifier.padding(20.dp), horizontalAlignment = Alignment.CenterHorizontally) {
                            Text("${diagnosticScore ?: 0}/100", fontSize = 36.sp, fontWeight = FontWeight.Bold)
                            Text("Verified Diagnostic Score", fontSize = 13.sp)
                            Spacer(Modifier.height(8.dp))
                            Text("$testsCount hardware modules successfully benchmarked.", fontSize = 12.sp)
                        }
                    }
                    Spacer(Modifier.height(24.dp))
                    Button(onClick = onComplete, modifier = Modifier.fillMaxWidth().height(48.dp)) {
                        Text("Finish")
                    }
                }
                "error" -> {
                    Text("Pairing Failed", fontSize = 20.sp, fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.error)
                    Spacer(Modifier.height(8.dp))
                    Text(errorMessage ?: "An error occurred", textAlign = TextAlign.Center, fontSize = 14.sp)
                    Spacer(Modifier.height(24.dp))
                    Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                        OutlinedButton(onClick = onBack) { Text("Cancel") }
                        Button(onClick = { stage = "input" }) { Text("Try Again") }
                    }
                }
            }
        }
    }
}
